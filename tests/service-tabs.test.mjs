import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const listeners = new Map(), requests = [], timers = new Map();
let nextId = 0;
const window = { postMessage: (message, origin) => requests.push({ message, origin }) };
const location = { origin:'http://127.0.0.1:47913' };
const context = vm.createContext({ window, location, crypto:{ randomUUID:() => String(++nextId) },
  addEventListener: (type, callback) => listeners.set(type, callback), removeEventListener: type => listeners.delete(type),
  setTimeout: callback => { const id = ++nextId; timers.set(id, callback); return id; }, clearTimeout: id => timers.delete(id) });
const source = fs.readFileSync(new URL('../ui/js/service-tabs.js', import.meta.url), 'utf8').replaceAll('export function', 'function');
vm.runInContext(source, context);
const open = vm.runInContext('openServiceTab', context);
const pending = open('https://www.youtube.com/tv');
const request = requests.at(-1);
assert.equal(request.origin, location.origin);
assert.equal(request.message.url, 'https://www.youtube.com/tv');
const receive = listeners.get('message');
receive({ source:{}, origin:location.origin, data:{ type:'bwos-open-result', requestId:request.message.requestId, result:{ ok:true } } });
assert.ok(listeners.has('message'), 'An unrelated window cannot acknowledge navigation');
receive({ source:window, origin:'https://untrusted.example', data:{ type:'bwos-open-result', requestId:request.message.requestId, result:{ ok:true } } });
assert.ok(listeners.has('message'), 'A foreign origin cannot acknowledge navigation');
receive({ source:window, origin:location.origin, data:{ type:'bwos-open-result', requestId:request.message.requestId, result:{ ok:true } } });
await pending;
assert.equal(listeners.size, 0, 'Successful navigation cleans up listeners');
assert.equal(timers.size, 0, 'Successful navigation clears its deadline');
const timeout = open('https://www.netflix.com/');
[...timers.values()][0]();
await assert.rejects(timeout, /Browser adapter unavailable/);
assert.equal(listeners.size, 0, 'An unavailable adapter is bounded and retryable');
const failed = open('https://www.netflix.com/');
const failureRequest = requests.at(-1);
listeners.get('message')({ source:window, origin:location.origin, data:{ type:'bwos-open-result', requestId:failureRequest.message.requestId, result:{ ok:false, error:'Player unavailable' } } });
await assert.rejects(failed, /Player unavailable/);
const sync=vm.runInContext('syncServiceRecommendations',context)('netflix');
const syncRequest=requests.at(-1);
assert.equal(syncRequest.message.type,'bwos-sync-recommendations');
assert.equal(syncRequest.message.service,'netflix');
assert.equal(syncRequest.message.url,undefined,'The UI cannot supply an arbitrary background navigation URL');
listeners.get('message')({source:window,origin:location.origin,data:{type:'bwos-open-result',requestId:syncRequest.message.requestId,result:{ok:true,count:5}}});
assert.equal((await sync).count,5);
console.log('PASS: retained-shell navigation bridge, origin checks, cleanup and bounded adapter failure');
